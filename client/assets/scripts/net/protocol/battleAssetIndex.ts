function framePaths(stem: string): string[] | null {
  const prefix = "battle/skill/" + stem + "/" + stem + "_";
  const indexed = SKILL_FRAME_INDEX[stem];
  if (indexed) {
    const paths: string[] = [];
    for (let i = 0; i < indexed.length; i++) paths.push(prefix + String(indexed[i]));
    return paths;
  }
  const count = SKILL_FRAME_COUNT[stem];
  if (!count) return null;
  const paths: string[] = [];
  for (let i = 0; i < count; i++) paths.push(prefix + String(i));
  return paths;
}

function skillIdText(skillId: number | null): string | null {
  if (typeof skillId !== "number" || !isFinite(skillId)) return null;
  return String(Math.floor(Math.abs(skillId)));
}

/** 这个技能号在 resources 里有帧时，返回要播的主套名。没有底套就用第一层。 */
export function skillStemForId(skillId: number | null): string | null {
  const id = skillIdText(skillId);
  if (!id) return null;
  const order = skillStemOrder(id);
  for (let i = 0; i < order.length; i++) {
    if (framePaths(order[i])) return order[i];
  }
  return null;
}

export function skillStemFrames(skillId: number | null): string[] | null {
  const stem = skillStemForId(skillId);
  if (!stem) return null;
  return framePaths(stem);
}

