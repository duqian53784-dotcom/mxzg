let attackTable: { [stem: string]: true } | null = null;
let standTable: { [stem: string]: true } | null = null;

function tableOf(csv: string): { [stem: string]: true } {
  const table: { [stem: string]: true } = {};
  const parts = csv.split(",");
  for (let i = 0; i < parts.length; i++) {
    if (parts[i]) table[parts[i]] = true;
  }
  return table;
}

/** 文件名对得上的英雄套。对不上返回 null，调用方用原来的三套默认。 */
export function heroSkinClips(stem: string): readonly HeroSkinClip[] | null {
  if (!attackTable) attackTable = tableOf(HERO_ATTACK_IDS);
  if (!standTable) standTable = tableOf(HERO_STAND_IDS);
  if (attackTable[stem]) return ATTACK_CLIPS;
  if (standTable[stem]) return STAND_CLIPS;
  return null;
}

